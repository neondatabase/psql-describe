#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const defaultDocDir = path.resolve(projectDir, '../postgres/doc/src/sgml/ref');

function usage() {
  return `Usage: node generate/create-help.mjs [options]

Generate JavaScript SQL-help data directly from the PostgreSQL SGML sources.

Options:
  --docdir PATH   PostgreSQL doc/src/sgml/ref directory
                  (default: ../postgres/doc/src/sgml/ref)
  --output PATH   Write to PATH instead of standard output
  -h, --help      Show this help
`;
}

function parseArgs(args) {
  let docDir = defaultDocDir;
  let output;

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];

    if (arg === '-h' || arg === '--help') {
      process.stdout.write(usage());
      process.exit(0);
    } else if (arg === '--docdir' || arg === '--output') {
      const value = args[++i];
      if (!value) throw new Error(`${arg} requires a path`);
      if (arg === '--docdir') docDir = path.resolve(value);
      else output = path.resolve(value);
    } else if (arg.startsWith('--docdir=')) {
      docDir = path.resolve(arg.slice('--docdir='.length));
    } else if (arg.startsWith('--output=')) {
      output = path.resolve(arg.slice('--output='.length));
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }

  return { docDir, output };
}

function extract(content, expression, field, filename) {
  const match = content.match(expression);
  if (!match) throw new Error(`could not find ${field} in ${filename}`);
  return match[1];
}

function textContent(s) {
  return s.replace(/<[^>]+>/g, '');
}

function readEntries(docDir) {
  const entries = new Map();

  for (const filename of fs.readdirSync(docDir).sort()) {
    if (!filename.endsWith('.sgml')) continue;

    const content = fs.readFileSync(path.join(docDir, filename), 'utf8');

    // Match create_help.pl: only SQL language statement reference pages
    // contribute entries to psql's \h help.
    if (!/<refmiscinfo>\s*SQL - Language Statements\s*<\/refmiscinfo>/i.test(content)) {
      continue;
    }

    const id = extract(
      content,
      /<refentry id="([a-z-]+)">/i,
      'refentry id',
      filename,
    );
    const names = [...content.matchAll(/<refname>\s*([a-z ]+?)\s*<\/refname>/gis)]
      .map(match => match[1]);
    const description = textContent(extract(
      content,
      /<refpurpose>\s*(.+?)\s*<\/refpurpose>/is,
      'refpurpose',
      filename,
    )).replace(/\s+/g, ' ');
    const synopsis = textContent(extract(
      content,
      /<synopsis>\s*(.+?)\s*<\/synopsis>/is,
      'synopsis',
      filename,
    ));

    if (names.length === 0) {
      throw new Error(`could not find refname in ${filename}`);
    }

    for (const name of names) {
      if (entries.has(name)) {
        throw new Error(`duplicate SQL-help command ${JSON.stringify(name)} in ${filename}`);
      }
      entries.set(name, [name, description, id, synopsis]);
    }
  }

  return [...entries.values()].sort((a, b) => {
    if (a[0] < b[0]) return -1;
    if (a[0] > b[0]) return 1;
    return 0;
  });
}

function generate(entries) {
  const rows = entries.map(entry => `  ${JSON.stringify(entry)},`).join('\n');

  return `/*
 * Do not edit this file by hand. It is generated from the PostgreSQL
 * SQL-language reference by generate/create-help.mjs.
 */

export const helpIndex = [
${rows}
];
`;
}

try {
  const { docDir, output } = parseArgs(process.argv.slice(2));
  const generated = generate(readEntries(docDir));

  if (output) fs.writeFileSync(output, generated);
  else process.stdout.write(generated);
} catch (error) {
  process.stderr.write(`create-help: ${error.message}\n\n${usage()}`);
  process.exitCode = 1;
}
